export const LANGS = ["en", "de"]

/** The language the page opens in: the saved choice, else the browser's, else English. */
export function initialLanguage() {
  try {
    const saved = localStorage.getItem("lang")
    if (LANGS.includes(saved)) return saved
  } catch {
    // Storage can be blocked; the browser language is a fine fallback.
  }
  return (navigator.language ?? "en").toLowerCase().startsWith("de") ? "de" : "en"
}

/**
 * Looks a text up and fills in {placeholders}. Unknown keys come back as the key itself, so a
 * missing translation is visible instead of blank.
 */
export function translate(lang, key, params = {}) {
  const text = DICT[lang]?.[key] ?? DICT.en[key] ?? key
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match))
}

/** Picks the singular or plural text for a count ("x.one" or "x.other"). */
export function translatePlural(lang, key, count, params = {}) {
  const form = new Intl.PluralRules(lang).select(count) === "one" ? "one" : "other"
  return translate(lang, `${key}.${form}`, { n: count, ...params })
}
